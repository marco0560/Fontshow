#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: scripts/benchmark.sh [light|medium|heavy]

Run on-demand Hyperfine benchmarks for the Fontshow pipeline stages.

Requirements:
  - run from the repository .venv
  - hyperfine available on PATH
  - benchmark fonts generated by scripts/setup_benchmark_fonts.sh
EOF
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  usage
  exit 0
fi

PROFILE="${1:-light}"
if [[ "${PROFILE}" != "light" && "${PROFILE}" != "medium" && "${PROFILE}" != "heavy" ]]; then
  usage >&2
  exit 2
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
EXPECTED_VENV="${REPO_ROOT}/.venv"

if [[ "${VIRTUAL_ENV:-}" != "${EXPECTED_VENV}" ]]; then
  printf 'error: activate the repository virtual environment first: source .venv/bin/activate\n' >&2
  exit 1
fi

if ! command -v hyperfine >/dev/null 2>&1; then
  printf 'error: hyperfine is required but was not found on PATH\n' >&2
  exit 1
fi

FONT_DIR="${REPO_ROOT}/tests/fixtures/fonts_dir"
RAW_INVENTORY="${REPO_ROOT}/tests/fixtures/raw_inventory.json"
SAMPLE_INVENTORY="${REPO_ROOT}/tests/fixtures/sample_inventory.json"
RESULTS_DIR="${REPO_ROOT}/tests/fixtures/benchmark_results"
RESULTS_JSON="${RESULTS_DIR}/fontshow-${PROFILE}.json"

"${SCRIPT_DIR}/setup_benchmark_fonts.sh" "${PROFILE}"
mkdir -p "${RESULTS_DIR}"
rm -rf "${RESULTS_DIR}/input-cache"

fontshow dump-fonts \
  --paths "${FONT_DIR}" \
  --cache-dir "${RESULTS_DIR}/input-cache" \
  --output "${RAW_INVENTORY}"
fontshow parse-inventory \
  "${RAW_INVENTORY}" \
  --output "${SAMPLE_INVENTORY}"

BENCH_TMP="$(mktemp -d)"
cleanup() {
  rm -rf "${BENCH_TMP}"
}
trap cleanup EXIT

hyperfine \
  --warmup 1 \
  --runs 3 \
  --export-json "${RESULTS_JSON}" \
  --command-name "dump-fonts (${PROFILE})" \
  --prepare "rm -rf '${BENCH_TMP}/dump' && mkdir -p '${BENCH_TMP}/dump/cache'" \
  "fontshow dump-fonts --paths '${FONT_DIR}' --cache-dir '${BENCH_TMP}/dump/cache' --output '${BENCH_TMP}/dump/raw_inventory.json'" \
  --command-name "parse-inventory (${PROFILE})" \
  --prepare "rm -rf '${BENCH_TMP}/parse' && mkdir -p '${BENCH_TMP}/parse'" \
  "fontshow parse-inventory '${RAW_INVENTORY}' --output '${BENCH_TMP}/parse/sample_inventory.json'" \
  --command-name "create-catalog (${PROFILE})" \
  --prepare "rm -rf '${BENCH_TMP}/catalog' && mkdir -p '${BENCH_TMP}/catalog'" \
  "fontshow create-catalog --inventory '${SAMPLE_INVENTORY}' --output '${BENCH_TMP}/catalog/catalog.tex'"

printf 'benchmark results written: %s\n' "${RESULTS_JSON}"
