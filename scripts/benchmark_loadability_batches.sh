#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<'EOF'
Usage: scripts/benchmark_loadability_batches.sh [light|medium|heavy] [jobs...]

Benchmark LuaLaTeX loadability probing with serial and bounded parallel
candidate-batch execution.

Requirements:
  - run from the repository .venv
  - hyperfine available on PATH
  - lualatex available on PATH
  - benchmark fonts generated by scripts/setup_benchmark_fonts.sh

Examples:
  scripts/benchmark_loadability_batches.sh light
  scripts/benchmark_loadability_batches.sh medium 1 2
  scripts/benchmark_loadability_batches.sh heavy 1 2 4
EOF
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  usage
  exit 0
fi

PROFILE="${1:-light}"
if [[ "${PROFILE}" != "light" && "${PROFILE}" != "medium" && "${PROFILE}" != "heavy" ]]; then
  usage >&2
  exit 2
fi
shift || true

if [[ "$#" -eq 0 ]]; then
  JOBS=(1 2 4)
else
  JOBS=("$@")
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
EXPECTED_VENV="${REPO_ROOT}/.venv"

if [[ "${VIRTUAL_ENV:-}" != "${EXPECTED_VENV}" ]]; then
  printf 'error: activate the repository virtual environment first: source .venv/bin/activate\n' >&2
  exit 1
fi

if ! command -v hyperfine >/dev/null 2>&1; then
  printf 'error: hyperfine is required but was not found on PATH\n' >&2
  exit 1
fi

if ! command -v lualatex >/dev/null 2>&1; then
  printf 'error: lualatex is required but was not found on PATH\n' >&2
  exit 1
fi

FONT_DIR="${REPO_ROOT}/tests/fixtures/fonts_dir"
RAW_INVENTORY="${REPO_ROOT}/tests/fixtures/loadability_benchmark_inventory.json"
RESULTS_DIR="${REPO_ROOT}/tests/fixtures/benchmark_results"
RESULTS_JSON="${RESULTS_DIR}/loadability-${PROFILE}.json"

"${SCRIPT_DIR}/setup_benchmark_fonts.sh" "${PROFILE}"
mkdir -p "${RESULTS_DIR}"
rm -rf "${RESULTS_DIR}/loadability-input-cache"

fontshow dump-fonts \
  --paths "${FONT_DIR}" \
  --cache-dir "${RESULTS_DIR}/loadability-input-cache" \
  --output "${RAW_INVENTORY}"

BENCH_TMP="$(mktemp -d)"
cleanup() {
  rm -rf "${BENCH_TMP}"
}
trap cleanup EXIT

HYPERFINE_ARGS=(
  --warmup 1
  --runs 3
  --export-json "${RESULTS_JSON}"
)

for job_count in "${JOBS[@]}"; do
  if ! [[ "${job_count}" =~ ^[0-9]+$ ]] || [[ "${job_count}" -lt 1 ]]; then
    printf 'error: jobs must be positive integers\n' >&2
    exit 2
  fi
  output_path="${BENCH_TMP}/loadability-jobs-${job_count}.json"
  HYPERFINE_ARGS+=(
    --command-name "loadability jobs=${job_count} (${PROFILE})"
    "python '${SCRIPT_DIR}/run_loadability_probe.py' '${RAW_INVENTORY}' --output '${output_path}' --jobs '${job_count}'"
  )
done

hyperfine "${HYPERFINE_ARGS[@]}"

printf 'loadability benchmark results written: %s\n' "${RESULTS_JSON}"
